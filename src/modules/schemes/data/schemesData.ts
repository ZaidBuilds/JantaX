/**
 * Builds the complete local government schemes summary for a PIN code.
 */
export function getSchemesSummaryForPin(pincode: string): LocalitySchemesSummary {
  const projects = generateSchemesForPin(pincode);
  const resolved = resolvePincode(pincode);

  let totalBudget = 0;
  let totalUtilized = 0;
  let underConstruction = 0;
  let completed = 0;
  let delayed = 0;
  let progressSum = 0;

  for (const p of projects) {
    totalBudget += p.totalSanctionedBudgetCr;
    totalUtilized += p.fundsUtilizedCr;
    progressSum += p.progressPercentage;

    if (p.status === 'Completed') completed += 1;
    else if (p.status === 'Under Construction') underConstruction += 1;
    else if (p.status === 'Delayed / Stalled') delayed += 1;
  }

  const overallProgressPercentage = projects.length > 0 ? Math.round(progressSum / projects.length) : 0;

  return {
    pincode,
    district: resolved.district,
    state: resolved.state,
    totalSchemesActive: new Set(projects.map((p) => p.schemeId)).size,
    totalProjectsCount: projects.length,
    totalSanctionedBudgetCr: Number(totalBudget.toFixed(2)),
    totalFundsUtilizedCr: Number(totalUtilized.toFixed(2)),
    overallProgressPercentage,
    projectsUnderConstruction: underConstruction,
    projectsCompleted: completed,
    projectsDelayed: delayed,
    projects,
  };
}
