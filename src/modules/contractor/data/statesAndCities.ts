// Flat list of all cities across all states
export const ALL_CITIES: CityInfo[] = INDIAN_STATES.flatMap(state => state.cities);

// Helper functions
export function getCitiesByState(stateId: string): CityInfo[] {
  if (!stateId || stateId === 'all-india') {
    return ALL_CITIES;
  }
  const foundState = INDIAN_STATES.find(s => s.id === stateId);
  return foundState ? foundState.cities : ALL_CITIES;
}

export function getStateById(stateId: string): StateInfo | undefined {
  return INDIAN_STATES.find(s => s.id === stateId);
}

export function getCityById(cityId: string): CityInfo | undefined {
  return ALL_CITIES.find(c => c.id === cityId);
}

export function getStateByCityId(cityId: string): StateInfo | undefined {
  const city = getCityById(cityId);
  if (!city) return undefined;
  return INDIAN_STATES.find(s => s.id === city.stateId);
}

